package com.halftonestudio;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Build 554 golden output + render-time regression over every selectable style.
 *
 * For each style at 3 in and 11 in, every exported cut sheet is reduced to a portable
 * signature: closed contours, circles, open paths and total enclosed cut area (mm²).
 * Contour counts must match exactly; area within 0.5 %. Any intended style change is
 * accepted by re-recording: VINYL_UPDATE_GOLDEN=1 bash tests/run-v3-golden-gate.sh
 * The exact SVG SHA-256 is recorded for diagnosis but only reported, never failed on,
 * because last-ulp floating point may differ between JVM builds.
 *
 * Render time per style is compared with tests/golden/style-render-budget.tsv. A case
 * fails only when it exceeds 4x its recorded time plus 1.5 s on two consecutive measurements, so the check catches
 * real algorithmic regressions without flaking on a busy machine.
 */
public final class V3StyleGoldenTest {
    static final Path GOLDEN=Paths.get("tests/golden/style-signatures.tsv");
    static final Path BUDGET=Paths.get("tests/golden/style-render-budget.tsv");
    static final float[] SIZES={76.2f,279.4f};

    static double polygonArea(float[] xy){
        double a=0;int n=xy.length/2;
        for(int i=0;i<n;i++){int j=(i+1)%n;a+=xy[2*i]*(double)xy[2*j+1]-xy[2*j]*(double)xy[2*i+1];}
        return Math.abs(a)/2;
    }
    static String sha(String s) throws Exception {
        byte[] d=MessageDigest.getInstance("SHA-256").digest(s.getBytes(StandardCharsets.UTF_8));
        StringBuilder b=new StringBuilder();for(int i=0;i<8;i++)b.append(String.format("%02x",d[i]));return b.toString();
    }
    static Map<String,String[]> read(Path p) throws IOException {
        Map<String,String[]> m=new LinkedHashMap<>();
        if(!Files.isRegularFile(p))return m;
        for(String line:Files.readAllLines(p)){
            if(line.isEmpty()||line.startsWith("#"))continue;
            String[] f=line.split("\t");m.put(f[0],f);
        }
        return m;
    }

    public static void main(String[] args) throws Exception {
        boolean update="1".equals(System.getenv("VINYL_UPDATE_GOLDEN"));
        int[] photo=V3AllStyleExportMatrixTest.portrait(60,60);
        Map<String,String[]> golden=read(GOLDEN),budget=read(BUDGET);
        List<String> sigOut=new ArrayList<>(),timeOut=new ArrayList<>(),failures=new ArrayList<>();
        int hashChanges=0,cases=0;
        sigOut.add("# key\tclosed\tcircles\topen\tarea_mm2\tsvg_sha256_prefix  (generated by V3StyleGoldenTest)");
        timeOut.add("# style@size\trender_ms  (generated by V3StyleGoldenTest)");
        for(float size:SIZES){
            for(int id=0;id<VinylStyleSuite.NAMES.length;id++){
                if(VinylStyleSuite.isRetiredStyleId(id)||!NewStyleVariantPolicy.selectable(id))continue;
                VinylStyleSuite.Config c=new VinylStyleSuite.Config();
                c.style=id;c.widthMm=size;c.detail=25;c.colorCount=4;c.minimumMm=.254f;c.draft=false;c.weightMm=.7f;
                long start=System.nanoTime();
                StyleKit.Result r=VinylStyleSuite.generate(photo,60,60,c);
                long ms=(System.nanoTime()-start)/1_000_000L;
                String caseKey=String.format(Locale.US,"%d@%.1f",id,size);
                timeOut.add(caseKey+"\t"+ms);cases++;
                String[] b=budget.get(caseKey);
                if(!update&&b!=null){
                    long allowed=Long.parseLong(b[1])*4+1500;
                    if(ms>allowed){ // re-measure once: scheduler/JIT noise, not algorithms, causes single slow runs
                        long again=System.nanoTime();VinylStyleSuite.generate(photo,60,60,c);
                        ms=Math.min(ms,(System.nanoTime()-again)/1_000_000L);
                    }
                    if(ms>allowed)failures.add(String.format(Locale.US,"PERF %s %s: %d ms > budget %d ms",caseKey,VinylStyleSuite.NAMES[id],ms,allowed));
                }
                for(int i=0;i<r.layers.size();i++){
                    StyleKit.Layer l=r.layers.get(i);if(l.loops.isEmpty()&&l.lines.isEmpty())continue;
                    String svg=NewStyleExport.layerSvg(r,i,false,0,3f,2f,null,.254f);
                    SvgDxfR13Exporter.SafetyGeometry g=SvgDxfR13Exporter.safetyGeometry(svg);
                    double area=0;for(float[] loop:g.closedLoops)area+=polygonArea(loop);
                    for(double[] circle:g.circles)area+=Math.PI*circle[2]*circle[2];
                    String key=caseKey+"#"+i;
                    String hash=sha(svg);
                    sigOut.add(String.format(Locale.US,"%s\t%d\t%d\t%d\t%.3f\t%s",key,g.closedLoops.size(),g.circles.size(),g.openPaths,area,hash));
                    if(update)continue;
                    String[] e=golden.remove(key);
                    if(e==null){failures.add("NEW sheet without golden: "+key+" "+VinylStyleSuite.NAMES[id]);continue;}
                    int closed=Integer.parseInt(e[1]),circles=Integer.parseInt(e[2]),open=Integer.parseInt(e[3]);
                    double gArea=Double.parseDouble(e[4]);
                    if(closed!=g.closedLoops.size()||circles!=g.circles.size()||open!=g.openPaths)
                        failures.add(String.format(Locale.US,"SHAPE %s %s: contours %d/%d/%d, golden %d/%d/%d",key,VinylStyleSuite.NAMES[id],
                            g.closedLoops.size(),g.circles.size(),g.openPaths,closed,circles,open));
                    else if(Math.abs(area-gArea)>Math.max(.5,gArea*.005))
                        failures.add(String.format(Locale.US,"AREA %s %s: %.2f mm² vs golden %.2f mm²",key,VinylStyleSuite.NAMES[id],area,gArea));
                    if(!hash.equals(e[5]))hashChanges++;
                }
            }
        }
        if(update){
            Files.write(GOLDEN,sigOut);Files.write(BUDGET,timeOut);
            System.out.printf(Locale.US,"RECORDED golden signatures for %d style-size cases (%d sheets) and render budgets%n",cases,sigOut.size()-1);
            return;
        }
        for(String missing:golden.keySet())failures.add("MISSING sheet present in golden: "+missing);
        if(!failures.isEmpty()){
            failures.forEach(System.out::println);
            throw new AssertionError(failures.size()+" golden/performance regressions. If intended, re-record with VINYL_UPDATE_GOLDEN=1 and review the diff.");
        }
        System.out.printf(Locale.US,"PASS 554 golden output: %d style-size cases, %d sheets match; %d exact-SVG hash drifts (informational); render times within budget%n",
            cases,sigOut.size()-1,hashChanges);
    }
}
