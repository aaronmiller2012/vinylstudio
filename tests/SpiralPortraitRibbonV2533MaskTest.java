package com.halftonestudio;

import java.util.regex.Matcher;
import java.util.regex.Pattern;

/** Host-only checks for the transparent-portrait failure seen on Samsung S22 Ultra. */
public final class SpiralPortraitRibbonV2533MaskTest {
    static void check(boolean ok,String msg){if(!ok)throw new AssertionError(msg);}
    static final int W=440,H=520;
    static int[] subject(boolean hole){
        int[] pixels=new int[W*H];
        for(int y=0;y<H;y++)for(int x=0;x<W;x++){
            // Transparent portrait with face/head and shoulders; photograph has
            // no opaque background, matching an ordinary cutout PNG.
            float nx=(x-W*.5f)/(W*.5f),ny=(y-H*.5f)/(H*.5f);
            boolean face=nx*nx/(.60f*.60f)+(ny+.25f)*(ny+.25f)/(.53f*.53f)<1;
            boolean shoulders=nx*nx/(.91f*.91f)+(ny-.69f)*(ny-.69f)/(.36f*.36f)<1;
            boolean visible=face||shoulders;
            if(hole&&x>W/2+35&&x<W/2+55&&y>H/2-38&&y<H/2-5)visible=false;
            int c=30+Math.min(195,Math.abs((x*11+y*7)%170));
            pixels[y*W+x]=((visible?255:0)<<24)|(c<<16)|(c<<8)|c;
        }
        return pixels;
    }
    static int count(String s,char c){int n=0;for(int i=0;i<s.length();i++)if(s.charAt(i)==c)n++;return n;}
    static void verifyAllContourPointsInside(int[] photo,String svg){
        // SVG generated by this exporter contains only M/Q/L/Z commands.
        Matcher m=Pattern.compile("[MLQ]([^MLQZ]+)").matcher(svg.substring(svg.indexOf(" d=\"")+4));
        Pattern nums=Pattern.compile("-?\\d+\\.\\d+");
        int count=0;
        while(m.find()){
            Matcher v=nums.matcher(m.group(1));
            while(v.find()){
                float x=Float.parseFloat(v.group());check(v.find(),"missing contour y");
                float y=Float.parseFloat(v.group());
                int px=(int)x,py=(int)y;
                check(px>=0&&py>=0&&px<W&&py<H,"contour escaped artboard");
                check((photo[py*W+px]>>>24)>=224,
                    "SVG path crossed photo transparency at "+x+","+y);
                count++;
            }
        }
        check(count>100,"did not examine enough photographic contours");
    }
    static SpiralPortraitRibbon.Options options(){
        SpiralPortraitRibbon.Options o=new SpiralPortraitRibbon.Options();
        o.widthMm=150;o.detail=70;o.minCutMm=.8f;o.minGapMm=.55f;return o;
    }
    public static void main(String[] args){
        int[] mask=subject(false);
        SpiralPortraitRibbon.Result result=SpiralPortraitRibbon.generate(mask,W,H,options());
        check(result.hasTransparentMask,"subject alpha not detected");
        check(result.cutPieces>1,"portrait should contain separate clipped cut pieces");
        check(result.cutPieces<4000,"too many paths for Cricut");
        check(result.cutPath.moves==result.cutPieces&&result.cutPath.closes==result.cutPieces,
            "SVG/Android contour count mismatch");
        String svg=result.svg();
        check(count(svg,'M')==result.cutPieces&&count(svg,'Z')==result.cutPieces,
            "multiple SVG contours not closed");
        check(!svg.contains("<clipPath")&&!svg.contains(" stroke=")&&!svg.contains("<mask"),
            "unsupported Cricut geometry");
        verifyAllContourPointsInside(mask,svg);
        int[] cutout=subject(true);
        SpiralPortraitRibbon.Result maskedHole=SpiralPortraitRibbon.generate(cutout,W,H,options());
        verifyAllContourPointsInside(cutout,maskedHole.svg());
        check(maskedHole.cutPieces>1,"interior alpha hole not clipped");
        int[] blank=new int[W*H];
        boolean rejected=false;
        try{SpiralPortraitRibbon.generate(blank,W,H,options());}
        catch(IllegalArgumentException e){rejected=e.getMessage().contains("No cut-safe spiral");}
        check(rejected,"blank transparent image should fail with actionable message");
        int[] opaque=subject(false);for(int i=0;i<opaque.length;i++)opaque[i]|=0xff000000;
        SpiralPortraitRibbon.Result full=SpiralPortraitRibbon.generate(opaque,W,H,options());
        check(!full.hasTransparentMask&&full.cutPieces==1,"opaque photo lost original connected spiral");
        System.out.println("PASS v2.53.3 alpha portrait: cutout, holes, no exposed-substrate cuts, closed SVG, opaque parity, blank failure");
        System.out.println("masked cut pieces="+result.cutPieces+" sampleCount="+result.samples+" svgBytes="+svg.length());
    }
}
